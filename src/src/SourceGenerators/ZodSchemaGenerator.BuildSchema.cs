partial class ZodSchemaGenerator
{
	static void BuildSchema(
		SchemaGenerationOutputContext outputContext,
		SourceProductionContext context,
		bool isPrimary
	)
	{
		context.CancellationToken.ThrowIfCancellationRequested();
		var writer = outputContext.Context.CreateCodeWriter();

		GenerateSchemaClass(outputContext, writer, isPrimary, context.CancellationToken);
		context.AddSource($"{outputContext.ZodSchema.TargetType.Name}Schema.g.cs", writer);

		context.CancellationToken.ThrowIfCancellationRequested();

		if (!isPrimary || outputContext.ZodSchema.ContainingTypes.Count > 0)
			return;

		var registrationWriter = outputContext.Context.CreateCodeWriter();
		registrationWriter.WriteAutoGeneratedHeader();
		registrationWriter.WriteLine(
			$"[assembly: global::{TypeLibrary.ZodSchemaGeneratedAttribute.MetadataFullName}(typeof({outputContext.ZodSchema.TargetType.AsTypeReference()}))]"
		);

		context.AddSource($"{outputContext.ZodSchema.TargetType.Name}SchemaRegistration.g.cs", registrationWriter);
	}

	static void GenerateSchemaClass(
		SchemaGenerationOutputContext outputContext,
		CodeWriter writer,
		bool isPrimary,
		CancellationToken cancellationToken
	)
	{
		cancellationToken.ThrowIfCancellationRequested();

		writer.WriteAutoGeneratedHeader();
		writer
			.WriteUsing("System")
			.WriteUsing("System.Collections.Generic")
			.WriteUsing("System.Collections.Immutable")
			.WriteUsing(TypeLibrary.ZodSharpCoreNamespace)
			.NewLine();

		using (writer.WriteBlockNamespaceScope(outputContext.ZodSchema.TargetType.AsTypeReference()))
		{
			writer.XmlSummary(
				$"Auto-generated schema validator for {CodeWriter.XmlSee(outputContext.ZodSchema.TargetType.Name)}.",
				"This class is generated at compile time for zero-allocation validation."
			);

			List<CodeWriter.BlockScope> wrapperBlocks = [];
			foreach (var containingTypeDeclaration in outputContext.ZodSchema.ContainingTypes)
				wrapperBlocks.Add(writer.WriteTypeScope(containingTypeDeclaration));

			using (
				writer.WriteClassScope(
					new TypeDeclarationOptions(
						outputContext.ZodSchema.SchemaType,
						outputContext.ZodSchema.TargetAccessibility
					)
					{
						IsPartial = true,
						IsStatic = true,
					}
				)
			)
			{
				writer.WriteField(
					new FieldDeclarationOptions(
						"EmptyPath",
						TypeLibrary
							.Collections.ImmutableArray.MakeGeneric(new TypeIdentity(SpecialType.System_String))
							.AsTypeReference(),
						TypeDeclarationAccessibility.Private
					)
					{
						IsStatic = true,
						IsReadOnly = true,
						Initializer = "[]",
					}
				);

				GeneratePathFields(writer, outputContext.ZodSchema, cancellationToken);
				GenerateStaticAttributeFields(writer, outputContext.ZodSchema, cancellationToken);
				GenerateValidationHelpers(writer, cancellationToken);

				GenerateValidateMethod(writer, outputContext.ZodSchema, cancellationToken);
				GenerateParseMethod(writer, outputContext.ZodSchema, cancellationToken);

				GenerateCompositionMethods(writer, outputContext.ZodSchema, cancellationToken);
			}

			if (isPrimary)
			{
				GenerateValidatorAdapter(writer, outputContext.ZodSchema, cancellationToken);
			}

			foreach (var block in wrapperBlocks)
				block.Dispose();
		}
	}

	static void GenerateValidatorAdapter(
		CodeWriter writer,
		ZodSchemaDescriptor schema,
		CancellationToken cancellationToken
	)
	{
		cancellationToken.ThrowIfCancellationRequested();

		var adapterName = $"{schema.TargetType.Name}SchemaValidator";
		var baseType = TypeLibrary.IZodSchemaValidator.MakeGeneric(schema.TargetType).AsTypeReference();

		writer.XmlSummary(
			$"DI-friendly validator adapter for {schema.TargetType.Name}, delegating to {schema.SchemaType.Name}."
		);

		writer.WriteClass(
			new TypeDeclarationOptions(adapterName)
			{
				Accessibility = schema.TargetAccessibility,
				IsPartial = true,
				BaseType = baseType,
			},
			body =>
			{
				body.WriteMethod(
					new MethodDeclarationOptions(
						"Validate",
						TypeLibrary.ValidationResult.MakeGeneric(schema.TargetType).AsTypeReference(),
						TypeDeclarationAccessibility.Public
					)
					{
						Parameters = [new ParameterDeclarationOptions("value", schema.TargetType.AsTypeReference())],
					},
					methodBody => methodBody.WriteReturn($"{schema.SchemaType.Name}.Validate(value)")
				);

				GenerateValidateAsyncMethod(body, schema, cancellationToken);
			}
		);
	}

	static void GenerateValidateAsyncMethod(
		CodeWriter writer,
		ZodSchemaDescriptor schema,
		CancellationToken cancellationToken
	)
	{
		cancellationToken.ThrowIfCancellationRequested();

		var customValidation = schema.CustomValidationMethod.Value;
		var returnType = TypeLibrary
			.ValueTask.MakeGeneric(TypeLibrary.ValidationResult.MakeGeneric(schema.TargetType))
			.AsTypeReference();
		var valueType = schema.TargetType.AsTypeReference();
		var cancellationTokenType = TypeLibrary.CancellationToken.AsTypeReference();

		var methodDeclaration = new MethodDeclarationOptions(
			"ValidateAsync",
			returnType,
			TypeDeclarationAccessibility.Public
		)
		{
			IsAsync = customValidation.InvocationKind != CustomValidationInvocationKind.None,
			Parameters =
			[
				new ParameterDeclarationOptions("value", valueType),
				new ParameterDeclarationOptions("cancellationToken", cancellationTokenType)
				{
					DefaultValue = "default",
				},
			],
		};

		writer.WriteMethod(
			methodDeclaration,
			method =>
			{
				if (customValidation.InvocationKind == CustomValidationInvocationKind.None)
				{
					method.WriteReturn(
						$"global::System.Threading.Tasks.ValueTask.FromResult({schema.SchemaType.Name}.Validate(value))"
					);
					return;
				}

				method.WriteLine($"var syncResult = {schema.SchemaType.Name}.Validate(value);");

				var prefix =
					customValidation.InvocationKind == CustomValidationInvocationKind.DefinedOnSchemaValidator
						? "this."
						: $"{schema.TargetType}.";

				method.WriteLine(
					$"var customResult = await {prefix}{customValidation.MethodName}(value, cancellationToken).ConfigureAwait(false);"
				);

				method.NewLine();
				method.WriteReturn(
					$"{TypeLibrary.ValidationResult.MakeGeneric(schema.TargetType)}.Merge(syncResult, customResult)"
				);
			}
		);
	}

	static void GenerateValidateMethod(
		CodeWriter writer,
		ZodSchemaDescriptor schema,
		CancellationToken cancellationToken
	)
	{
		cancellationToken.ThrowIfCancellationRequested();

		writer.XmlSummary("Validates an instance of the target type.");
		var methodDeclaration = new MethodDeclarationOptions(
			"Validate",
			TypeLibrary.ValidationResult.MakeGeneric(schema.TargetType).AsTypeReference(),
			TypeDeclarationAccessibility.Public
		)
		{
			IsStatic = true,
			Parameters = [new ParameterDeclarationOptions("value", schema.TargetType.AsTypeReference())],
		};

		writer.WriteMethod(
			methodDeclaration,
			method =>
			{
				if (schema.TargetCanBeNull)
				{
					method.WriteBlock(
						"if (value == null)",
						ifBody =>
							ifBody.WriteReturn(
								$"{TypeLibrary.ValidationResult.MakeGeneric(schema.TargetType)}.Failure({TypeLibrary.ValidationError}.Create({CodeGenHelpers.Quote("invalid_type")}, {CodeGenHelpers.Quote("Value cannot be null")}, EmptyPath))"
							)
					);
				}

				var errorsListType = TypeLibrary
					.Collections.List.MakeGeneric(TypeLibrary.ValidationError)
					.AsTypeReference()
					.Nullable();
				method.NewLine();
				method.WriteLine($"{errorsListType} errors = null;");

				foreach (var property in schema.Properties)
				{
					if (property.ShouldProcess)
						GeneratePropertyValidation(writer, property.Value, cancellationToken);
				}

				method.WriteBlock(
					"if (errors is not null)",
					ifBody =>
						ifBody.WriteReturn(
							$"{TypeLibrary.ValidationResult.MakeGeneric(schema.TargetType)}.Failure(errors)"
						)
				);

				method.NewLine();
				method.WriteReturn($"{TypeLibrary.ValidationResult.MakeGeneric(schema.TargetType)}.Success(value)");
			}
		);

		writer.NewLine();
	}

	static void GenerateParseMethod(CodeWriter writer, ZodSchemaDescriptor schema, CancellationToken cancellationToken)
	{
		cancellationToken.ThrowIfCancellationRequested();

		writer.XmlSummary("Validates and returns the value, throwing an exception if validation fails.");
		writer.XmlParam("value", "The value to validate and return.");
		writer.XmlReturn("The validated value.");

		var methodDeclaration = new MethodDeclarationOptions(
			"Parse",
			schema.TargetType.AsTypeReference(),
			TypeDeclarationAccessibility.Public
		)
		{
			IsStatic = true,
			Parameters = [new ParameterDeclarationOptions("value", schema.TargetType.AsTypeReference())],
		};

		writer.WriteMethod(
			methodDeclaration,
			methodBody => methodBody.WriteReturn("Validate(value).GetValueOrThrow()")
		);
	}

	static void GenerateCompositionMethods(
		CodeWriter writer,
		ZodSchemaDescriptor schema,
		CancellationToken cancellationToken
	)
	{
		cancellationToken.ThrowIfCancellationRequested();

		var validationResultType = TypeLibrary.ValidationResult.MakeGeneric(schema.TargetType).AsTypeReference();
		var targetType = schema.TargetType.AsTypeReference();
		var funcType = new TypeIdentity(typeof(Func<,>))
			.MakeGeneric(schema.TargetType, new TypeIdentity(SpecialType.System_Boolean))
			.AsTypeReference();
		var stringType = new TypeIdentity(SpecialType.System_String).AsTypeReference().Nullable();

		void WriteFailure(CodeWriter body, string fallbackMessage) =>
			body.WriteReturn(
				$"{validationResultType}.Failure({TypeLibrary.ValidationError}.Create({CodeGenHelpers.Quote("validation_failed")}, message ?? {CodeGenHelpers.Quote(fallbackMessage)}, EmptyPath))"
			);

		writer.NewLine();
		writer.XmlSummary(
			"Validates the value and then requires an additional predicate to pass (value-first .and()).",
			"Equivalent to Zod's .and() semantics applied to a value."
		);

		writer.WriteMethod(
			new MethodDeclarationOptions("ApplyAnd", validationResultType, TypeDeclarationAccessibility.Public)
			{
				IsStatic = true,
				Parameters =
				[
					new ParameterDeclarationOptions("value", targetType),
					new ParameterDeclarationOptions("additionalValidation", funcType),
					new ParameterDeclarationOptions("message", stringType) { DefaultValue = "null" },
				],
			},
			method =>
			{
				method.WriteLine("var result = Validate(value);");
				method.WriteBlock("if (!result.IsSuccess)", ifBody => ifBody.WriteReturn("result"));
				method.NewLine();
				method.WriteBlock(
					"if (!additionalValidation(value))",
					ifBody => WriteFailure(ifBody, $"Additional validation failed for {schema.TargetType.Name}")
				);
				method.NewLine();
				method.WriteReturn("result");
			}
		);

		writer.NewLine();
		writer.XmlSummary(
			"Validates the value and accepts it if either the schema or an alternative predicate passes (value-first .or()).",
			"Equivalent to Zod's .or() semantics applied to a value."
		);

		writer.WriteMethod(
			new MethodDeclarationOptions("ApplyOr", validationResultType, TypeDeclarationAccessibility.Public)
			{
				IsStatic = true,
				Parameters =
				[
					new ParameterDeclarationOptions("value", targetType),
					new ParameterDeclarationOptions("alternativeValidation", funcType),
					new ParameterDeclarationOptions("message", stringType) { DefaultValue = "null" },
				],
			},
			method =>
			{
				method.WriteLine("var result = Validate(value);");
				method.WriteBlock("if (result.IsSuccess)", ifBody => ifBody.WriteReturn("result"));
				method.NewLine();
				method.WriteBlock(
					"if (alternativeValidation(value))",
					ifBody => ifBody.WriteReturn($"{validationResultType}.Success(value)")
				);
				method.NewLine();
				WriteFailure(method, $"Neither validation passed for {schema.TargetType.Name}");
			}
		);

		writer.NewLine();
		writer.XmlSummary(
			"Validates the value and then runs a custom refinement predicate (value-first .refine()).",
			"Equivalent to Zod's .refine() semantics applied to a value."
		);

		writer.WriteMethod(
			new MethodDeclarationOptions("ApplyRefine", validationResultType, TypeDeclarationAccessibility.Public)
			{
				IsStatic = true,
				Parameters =
				[
					new ParameterDeclarationOptions("value", targetType),
					new ParameterDeclarationOptions("refinement", funcType),
					new ParameterDeclarationOptions("message", stringType) { DefaultValue = "null" },
				],
			},
			method =>
			{
				method.WriteLine("var result = Validate(value);");
				method.WriteBlock("if (!result.IsSuccess)", ifBody => ifBody.WriteReturn("result"));
				method.NewLine();
				method.WriteBlock(
					"if (!refinement(value))",
					ifBody => WriteFailure(ifBody, $"Refinement validation failed for {schema.TargetType.Name}")
				);
				method.NewLine();
				method.WriteReturn("result");
			}
		);

		writer.NewLine();
	}

	static void GeneratePropertyValidation(
		CodeWriter writer,
		ZodPropertyDescriptor property,
		CancellationToken cancellationToken
	)
	{
		cancellationToken.ThrowIfCancellationRequested();

		var propertyName = property.Name;
		var attributes = property.ValidationAttributes;
		CodeWriter.BlockScope? block = null;

		if (property.CanBeNull && attributes.Required.ShouldProcess && attributes.Required.Value.Exists)
		{
			var required = attributes.Required.Value;
			var isStringAndAllowEmptyStrings =
				property.PropertyType.SpecialType == SpecialType.System_String && required.AllowEmptyStrings;
			var localErrorMessage = isStringAndAllowEmptyStrings
				? "Field '{0}' is required and cannot be null or empty"
				: "Required field '{0}' is null";
			var errorMessage = string.Format(
				CultureInfo.InvariantCulture,
				required.ValidationAttribute.ErrorMessage ?? localErrorMessage,
				propertyName
			);
			var comparison = isStringAndAllowEmptyStrings
				? $"string.IsNullOrEmpty(value.{propertyName})"
				: $"value.{propertyName} == null";

			writer.WriteRule(propertyName, comparison, "missing_field", errorMessage);
			block = writer.OpenBlockScope("else");
			GenerateValueSetValidations(writer, property);
		}
		else
		{
			GenerateValueSetValidations(writer, property);
			if (property.CanBeNull)
				block = writer.OpenBlockScope($"if (value.{propertyName} != null)");
		}

		GenerateTypeSpecificValidations(writer, property);
		block?.Dispose();

		GenerateCompareValidation(writer, property);
		writer.NewLine();
	}

	static void GenerateTypeSpecificValidations(CodeWriter writer, ZodPropertyDescriptor property)
	{
		switch (property.ValidationKind)
		{
			case PropertyValidationKind.String:
				GenerateStringValidations(writer, property);
				break;
			case PropertyValidationKind.Numeric:
				GenerateNumericValidations(writer, property);
				break;
			case PropertyValidationKind.Collection:
				GenerateCollectionValidations(writer, property);
				break;
			case PropertyValidationKind.Complex:
				GenerateComplexTypeValidation(writer, property);
				break;
			case PropertyValidationKind.Unsupported:
				break;
			default:
				break;
		}
	}

	static void GenerateCompareValidation(CodeWriter writer, ZodPropertyDescriptor property)
	{
		var compareAttribute = property.ValidationAttributes.Compare;
		if (!compareAttribute.ShouldProcess || !compareAttribute.Value.Exists)
			return;

		var compare = compareAttribute.Value;
		var displayName = property.DisplayName;
		var otherDisplayName = compare.OtherPropertyDisplayName ?? compare.OtherProperty;

		var messageExpression = BuildErrorMessageExpression(
			compare.ValidationAttribute,
			"Field '{0}' must match '{1}'.",
			CodeGenHelpers.Quote(displayName),
			CodeGenHelpers.Quote(otherDisplayName)
		);

		writer.WriteBlock(
			$"if (!global::System.Collections.Generic.EqualityComparer<object>.Default.Equals(value.{property.Name}, value.{compare.OtherProperty}))",
			ifBody =>
				WriteValidationError(
					ifBody,
					"mismatch",
					messageExpression,
					CodeGenHelpers.GetPathFieldName(property.Name)
				)
		);

		writer.NewLine();
	}

	static void GenerateCollectionElementValidation(CodeWriter writer, ZodPropertyDescriptor property)
	{
		if (property.NestedSchemaType is null)
			return;

		var propertyName = property.Name;
		var collectionValueName = CodeGenHelpers.GetLocalIdentifier(propertyName, "Collection");
		var itemValueName = CodeGenHelpers.GetLocalIdentifier(propertyName, "Item");
		var itemResultName = CodeGenHelpers.GetLocalIdentifier(propertyName, "ItemResult");
		var indexName = CodeGenHelpers.GetLocalIdentifier(propertyName, "Index");
		var schemaType = property.NestedSchemaType.Value;

		writer.WriteLine($"var {collectionValueName} = value.{propertyName};");
		using (writer.OpenBlockScope($"if ({collectionValueName} is not null)"))
		{
			writer.WriteLine($"var {indexName} = 0;");
			using (writer.OpenBlockScope($"foreach (var {itemValueName} in {collectionValueName})"))
			{
				if (property.ElementTypeCanBeNull)
				{
					writer.WriteLine($"if ({itemValueName} is null)");
					writer.WriteLine("{");
					writer.WriteLine($"\t{indexName}++;");
					writer.WriteLine("\tcontinue;");
					writer.WriteLine("}");
				}

				writer.WriteLine($"var {itemResultName} = {schemaType}.Validate({itemValueName});");
				using (writer.OpenBlockScope($"if (!{itemResultName}.IsSuccess)"))
				{
					writer.WriteLine(
						$"AddNestedErrors(ref errors, {itemResultName}, {CodeGenHelpers.Quote(propertyName)}, {indexName});"
					);
				}

				writer.WriteLine($"{indexName}++;");
			}
		}

		writer.NewLine();
	}

	static void GenerateComplexTypeValidation(CodeWriter writer, ZodPropertyDescriptor property)
	{
		if (property.NestedSchemaType is null)
			return;

		var propertyName = property.Name;
		var propertyValueName = CodeGenHelpers.GetLocalIdentifier(propertyName, "Value");
		var nestedResultName = CodeGenHelpers.GetLocalIdentifier(propertyName, "Result");
		var schemaType = property.NestedSchemaType.Value;

		writer.WriteLine($"var {propertyValueName} = value.{propertyName};");
		if (property.CanBeNull)
		{
			using (writer.OpenBlockScope($"if ({propertyValueName} is not null)"))
			{
				writer.WriteLine($"var {nestedResultName} = {schemaType}.Validate({propertyValueName});");
				using (writer.OpenBlockScope($"if (!{nestedResultName}.IsSuccess)"))
				{
					writer.WriteLine(
						$"AddNestedErrors(ref errors, {nestedResultName}, {CodeGenHelpers.Quote(propertyName)});"
					);
				}
			}
		}
		else
		{
			writer.WriteLine($"var {nestedResultName} = {schemaType}.Validate({propertyValueName});");
			using (writer.OpenBlockScope($"if (!{nestedResultName}.IsSuccess)"))
			{
				writer.WriteLine(
					$"AddNestedErrors(ref errors, {nestedResultName}, {CodeGenHelpers.Quote(propertyName)});"
				);
			}
		}
	}

	static void GeneratePathFields(CodeWriter writer, ZodSchemaDescriptor schema, CancellationToken cancellationToken)
	{
		var pathFieldType = TypeLibrary
			.Collections.ImmutableArray.MakeGeneric(new TypeIdentity(SpecialType.System_String))
			.AsTypeReference();

		foreach (var property in schema.Properties)
		{
			cancellationToken.ThrowIfCancellationRequested();
			if (!property.ShouldProcess)
				continue;

			writer.WriteField(
				new FieldDeclarationOptions(
					CodeGenHelpers.GetPathFieldName(property.Value.Name),
					pathFieldType,
					TypeDeclarationAccessibility.Private
				)
				{
					IsStatic = true,
					IsReadOnly = true,
					Initializer =
						$"{TypeLibrary.Collections.ImmutableArray}.Create({CodeGenHelpers.Quote(property.Value.Name)})",
				}
			);
		}
	}

	static void GenerateStaticAttributeFields(
		CodeWriter writer,
		ZodSchemaDescriptor schema,
		CancellationToken cancellationToken
	)
	{
		var regexType = new TypeIdentity("Regex", "System.Text.RegularExpressions").AsTypeReference();

		foreach (var property in schema.Properties)
		{
			cancellationToken.ThrowIfCancellationRequested();
			if (!property.ShouldProcess)
				continue;

			var prop = property.Value;

			if (prop.ValidationAttributes.RegularExpression.ShouldProcess)
			{
				var pattern = prop.ValidationAttributes.RegularExpression.Value.Pattern;
				writer.WriteField(
					new FieldDeclarationOptions(
						GetRegexFieldName(prop.Name),
						regexType,
						TypeDeclarationAccessibility.Private
					)
					{
						IsStatic = true,
						IsReadOnly = true,
						Initializer =
							$"new({CodeGenHelpers.Quote(pattern!)}, global::System.Text.RegularExpressions.RegexOptions.CultureInvariant)",
					}
				);
			}

			if (prop.ValidationAttributes.Range.ShouldProcess)
			{
				var propertyType = prop.PropertyType.AsTypeReference();
				var range = prop.ValidationAttributes.Range.Value;
				writer.WriteField(
					new FieldDeclarationOptions(
						GetRangeMinimumFieldName(prop.Name),
						propertyType,
						TypeDeclarationAccessibility.Private
					)
					{
						IsStatic = true,
						IsReadOnly = true,
						Initializer = range.MinimumExpression!,
					}
				);
				writer.WriteField(
					new FieldDeclarationOptions(
						GetRangeMaximumFieldName(prop.Name),
						propertyType,
						TypeDeclarationAccessibility.Private
					)
					{
						IsStatic = true,
						IsReadOnly = true,
						Initializer = range.MaximumExpression!,
					}
				);
			}
		}

		writer.NewLine();
	}

	static void GenerateValidationHelpers(CodeWriter writer, CancellationToken cancellationToken)
	{
		cancellationToken.ThrowIfCancellationRequested();

		var listOfErrorsType = TypeLibrary.Collections.List.MakeGeneric(TypeLibrary.ValidationError).AsTypeReference();
		var errorType = TypeLibrary.ValidationError.AsTypeReference();
		var immutableArrayType = TypeLibrary.Collections.ImmutableArray;
		var typeParameterT = new TypeIdentity("T", null).AsTypeReference();

		writer.WriteMethod(
			new MethodDeclarationOptions("AddError", TypeDeclarationAccessibility.Private)
			{
				IsStatic = true,
				Parameters =
				[
					new ParameterDeclarationOptions("errors", listOfErrorsType.Nullable())
					{
						Modifier = ParameterModifier.Ref,
					},
					new ParameterDeclarationOptions("error", errorType),
				],
			},
			body => body.WriteLine($"(errors ??= new {listOfErrorsType}()).Add(error);")
		);

		writer.WriteMethod(
			new MethodDeclarationOptions("AddNestedErrors", TypeDeclarationAccessibility.Private)
			{
				IsStatic = true,
				GenericTypes = [new GenericTypeParameterOptions("T")],
				Parameters =
				[
					new ParameterDeclarationOptions("errors", listOfErrorsType.Nullable())
					{
						Modifier = ParameterModifier.Ref,
					},
					new ParameterDeclarationOptions(
						"nestedResult",
						TypeLibrary.ValidationResult.MakeGeneric(typeParameterT).AsTypeReference()
					),
					new ParameterDeclarationOptions(
						"prefix",
						new TypeIdentity(SpecialType.System_String).AsTypeReference()
					),
				],
			},
			body =>
				body.WriteBlock(
					"foreach (var error in nestedResult.Errors)",
					foreachBody =>
						foreachBody.WriteLine(
							$"AddError(ref errors, {TypeLibrary.ValidationError}.Create(error.Code, error.Message, {immutableArrayType}.Create(prefix).AddRange(error.Path), error.Parameters, error.Origin, error.Minimum, error.Maximum, error.Inclusive));"
						)
				)
		);

		writer.WriteMethod(
			new MethodDeclarationOptions("AddNestedErrors", TypeDeclarationAccessibility.Private)
			{
				IsStatic = true,
				GenericTypes = [new GenericTypeParameterOptions("T")],
				Parameters =
				[
					new ParameterDeclarationOptions("errors", listOfErrorsType.Nullable())
					{
						Modifier = ParameterModifier.Ref,
					},
					new ParameterDeclarationOptions(
						"nestedResult",
						TypeLibrary.ValidationResult.MakeGeneric(typeParameterT).AsTypeReference()
					),
					new ParameterDeclarationOptions(
						"prefix",
						new TypeIdentity(SpecialType.System_String).AsTypeReference()
					),
					new ParameterDeclarationOptions(
						"index",
						new TypeIdentity(SpecialType.System_Int32).AsTypeReference()
					),
				],
			},
			body =>
				body.WriteBlock(
					"foreach (var error in nestedResult.Errors)",
					foreachBody =>
						foreachBody.WriteLine(
							$"AddError(ref errors, {TypeLibrary.ValidationError}.Create(error.Code, error.Message, {immutableArrayType}.Create(prefix, index.ToString()).AddRange(error.Path), error.Parameters, error.Origin, error.Minimum, error.Maximum, error.Inclusive));"
						)
				)
		);

		writer.NewLine();
		writer.WriteMethod(
			new MethodDeclarationOptions(
				"FormatCount",
				new TypeIdentity(SpecialType.System_String).AsTypeReference(),
				TypeDeclarationAccessibility.Private
			)
			{
				IsStatic = true,
				Parameters =
				[
					new ParameterDeclarationOptions(
						"count",
						new TypeIdentity(SpecialType.System_Int32).AsTypeReference()
					),
					new ParameterDeclarationOptions(
						"singularNoun",
						new TypeIdentity(SpecialType.System_String).AsTypeReference()
					),
					new ParameterDeclarationOptions(
						"pluralNoun",
						new TypeIdentity(SpecialType.System_String).AsTypeReference()
					),
				],
			},
			body => body.WriteReturn("count == 1 ? $\"1 {singularNoun}\" : $\"{count} {pluralNoun}\"")
		);

		writer.NewLine();
	}
